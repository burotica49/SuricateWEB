// Contrat d'un adaptateur de base (voir src/store/sqlite.js) : les mêmes tests valent pour tous les moteurs.
//
// Ici, ils tournent sur SQLite (test/store-sqlite.test.js). Le dépôt de la version hébergée les rejoue sur PostgreSQL :
//
//     import { adapterContract } from '<cœur>/test-support/adapter-contract.js';
//     adapterContract({ name: 'postgres', open: async () => openPostgres(url) });
//
// `open()` renvoie un adaptateur NEUF et vide. Les tests créent leurs propres tables (préfixe « c_ »), avec le DDL du moteur.
import { test } from 'node:test';
import assert from 'node:assert/strict';

const ID = { sqlite: 'INTEGER PRIMARY KEY AUTOINCREMENT', postgres: 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' };
const BIG = { sqlite: 'INTEGER', postgres: 'BIGINT' };
const BLOB = { sqlite: 'BLOB', postgres: 'BYTEA' };

export function adapterContract({ name, open }) {
  const t = (title, fn) =>
    test(`adaptateur ${name} : ${title}`, async () => {
      const db = await open();
      try {
        const id = ID[db.dialect];
        const big = BIG[db.dialect];
        await db.exec(`
          CREATE TABLE c_items (id ${id}, name TEXT NOT NULL, grp ${big}, ts ${big}, ok INTEGER NOT NULL DEFAULT 0, data ${BLOB[db.dialect]});
          CREATE TABLE c_periods (id ${id}, start ${big} NOT NULL, "end" ${big});
          CREATE TABLE c_stats (item ${big} NOT NULL, day INTEGER NOT NULL, n INTEGER NOT NULL DEFAULT 0, min_ms INTEGER, max_ms INTEGER, PRIMARY KEY (item, day));
        `);
        await fn(db);
      } finally {
        await db.close();
      }
    });

  t('insert renvoie l\'identifiant créé (un nombre qui croît)', async (db) => {
    const a = await db.insert('INSERT INTO c_items(name) VALUES(?)', ['a']);
    const b = await db.insert('INSERT INTO c_items(name) VALUES(?)', ['b']);
    assert.equal(typeof a, 'number');
    assert.ok(b > a);
  });

  t('get / all / run : paramètres, absence de ligne, lignes touchées', async (db) => {
    await db.run('INSERT INTO c_items(name, ok) VALUES(?,?)', ['x', 1]);
    await db.run('INSERT INTO c_items(name, ok) VALUES(?,?)', ['y', 0]);
    assert.equal((await db.get('SELECT name FROM c_items WHERE ok = ?', [1])).name, 'x');
    assert.equal(await db.get('SELECT name FROM c_items WHERE ok = ?', [9]), undefined);
    assert.deepEqual((await db.all('SELECT name FROM c_items ORDER BY name')).map((r) => r.name), ['x', 'y']);
    assert.deepEqual(await db.run('UPDATE c_items SET ok = 5 WHERE ok < ?', [2]), { changes: 2 });
    assert.deepEqual(await db.run('DELETE FROM c_items WHERE name = ?', ['absent']), { changes: 0 });
  });

  t('NULL : IS NOT DISTINCT FROM / IS DISTINCT FROM le comparent comme une valeur', async (db) => {
    await db.run('INSERT INTO c_items(name, grp) VALUES(?,?)', ['sans', null]);
    await db.run('INSERT INTO c_items(name, grp) VALUES(?,?)', ['avec', 3]);
    const none = await db.all('SELECT name FROM c_items WHERE grp IS NOT DISTINCT FROM ?', [null]);
    const three = await db.all('SELECT name FROM c_items WHERE grp IS NOT DISTINCT FROM ?', [3]);
    const other = await db.all('SELECT name FROM c_items WHERE grp IS DISTINCT FROM ? ORDER BY name', [3]);
    assert.deepEqual(none.map((r) => r.name), ['sans']);
    assert.deepEqual(three.map((r) => r.name), ['avec']);
    assert.deepEqual(other.map((r) => r.name), ['sans']);
  });

  t('nombres : horodatages en ms, COUNT, SUM, AVG, MIN, MAX reviennent en Number', async (db) => {
    const ts = Date.now();
    await db.run('INSERT INTO c_items(name, ts) VALUES(?,?)', ['a', ts]);
    await db.run('INSERT INTO c_items(name, ts) VALUES(?,?)', ['b', ts + 10]);
    const row = await db.get('SELECT ts FROM c_items WHERE name = ?', ['a']);
    assert.strictEqual(row.ts, ts);
    const agg = await db.get('SELECT COUNT(*) n, SUM(ts) s, AVG(ts) a, MIN(ts) lo, MAX(ts) hi FROM c_items');
    for (const k of ['n', 's', 'a', 'lo', 'hi']) assert.equal(typeof agg[k], 'number', k);
    assert.equal(agg.n, 2);
    assert.equal(agg.hi - agg.lo, 10);
  });

  t('octets : un Buffer (gzip) fait l\'aller-retour', async (db) => {
    const bytes = Buffer.from([0, 1, 2, 250, 255, 0, 7]);
    await db.run('INSERT INTO c_items(name, data) VALUES(?,?)', ['bin', bytes]);
    const back = (await db.get('SELECT data FROM c_items WHERE name = ?', ['bin'])).data;
    assert.ok(Buffer.from(back).equals(bytes));
  });

  t('« end » entre guillemets, ORDER BY LOWER, LIMIT très grand avec OFFSET', async (db) => {
    await db.run('INSERT INTO c_periods(start, "end") VALUES(?,?)', [1, null]);
    await db.run('INSERT INTO c_periods(start, "end") VALUES(?,?)', [2, 9]);
    const open = await db.get('SELECT start FROM c_periods WHERE "end" IS NULL');
    assert.equal(open.start, 1);
    assert.equal((await db.get('SELECT MAX("end") e FROM c_periods')).e, 9);

    for (const n of ['b', 'A', 'c']) await db.run('INSERT INTO c_items(name) VALUES(?)', [n]);
    assert.deepEqual((await db.all('SELECT name FROM c_items ORDER BY LOWER(name)')).map((r) => r.name), ['A', 'b', 'c']);
    assert.deepEqual((await db.all('SELECT name FROM c_items ORDER BY id DESC LIMIT 1000000000 OFFSET ?', [1])).map((r) => r.name), ['A', 'b']);
  });

  t('upsert ON CONFLICT avec colonnes qualifiées et CASE (le schéma des agrégats par jour)', async (db) => {
    const sql = `
      INSERT INTO c_stats(item, day, n, min_ms, max_ms) VALUES(?,?,1,?,?)
      ON CONFLICT(item, day) DO UPDATE SET
        n = c_stats.n + 1,
        min_ms = CASE WHEN excluded.min_ms IS NULL THEN c_stats.min_ms WHEN c_stats.min_ms IS NULL THEN excluded.min_ms
                      WHEN excluded.min_ms < c_stats.min_ms THEN excluded.min_ms ELSE c_stats.min_ms END,
        max_ms = CASE WHEN excluded.max_ms IS NULL THEN c_stats.max_ms WHEN c_stats.max_ms IS NULL THEN excluded.max_ms
                      WHEN excluded.max_ms > c_stats.max_ms THEN excluded.max_ms ELSE c_stats.max_ms END`;
    await db.run(sql, [1, 100, 200, 200]);
    await db.run(sql, [1, 100, 120, 120]);
    await db.run(sql, [1, 100, 300, 300]);
    await db.run(sql, [1, 100, null, null]); // échec : pas de temps de réponse, le compteur avance seul
    assert.deepEqual({ ...(await db.get('SELECT n, min_ms, max_ms FROM c_stats WHERE item = ?', [1])) }, { n: 4, min_ms: 120, max_ms: 300 });
  });

  t('exec : plusieurs instructions d\'un coup', async (db) => {
    await db.exec("INSERT INTO c_items(name) VALUES('p'); INSERT INTO c_items(name) VALUES('q');");
    assert.equal((await db.get('SELECT COUNT(*) n FROM c_items')).n, 2);
  });

  t('transaction : validée si tout réussit, annulée si la fonction lève', async (db) => {
    const out = await db.transaction(async (tx) => {
      await tx.run('INSERT INTO c_items(name) VALUES(?)', ['ok1']);
      await tx.run('INSERT INTO c_items(name) VALUES(?)', ['ok2']);
      return 'fini';
    });
    assert.equal(out, 'fini');
    assert.equal((await db.get('SELECT COUNT(*) n FROM c_items')).n, 2);

    await assert.rejects(
      async () => db.transaction(async (tx) => {
        await tx.run('INSERT INTO c_items(name) VALUES(?)', ['perdu']);
        throw new Error('échec voulu');
      }),
      /échec voulu/,
    );
    assert.equal(await db.get('SELECT name FROM c_items WHERE name = ?', ['perdu']), undefined);
    assert.equal((await db.get('SELECT COUNT(*) n FROM c_items')).n, 2);
  });

  t('transaction : la lecture dans la transaction voit ses propres écritures', async (db) => {
    await db.transaction(async (tx) => {
      await tx.run('INSERT INTO c_items(name, grp) VALUES(?,?)', ['t', 7]);
      assert.equal((await tx.get('SELECT name FROM c_items WHERE grp = ?', [7])).name, 't');
    });
  });
}
